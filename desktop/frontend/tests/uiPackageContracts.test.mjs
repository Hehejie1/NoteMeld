import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { test } from 'node:test'
import path from 'node:path'

const root = path.resolve(new URL('../../..', import.meta.url).pathname)
const frontend = path.join(root, 'desktop/frontend')

test('desktop and Cloud Web consume the independent ui-web workspace package', async () => {
  const manifest = JSON.parse(await readFile(path.join(frontend, 'packages/ui-web/package.json'), 'utf8'))
  const packageIndex = await readFile(path.join(frontend, 'packages/ui-web/src/index.ts'), 'utf8')
  const packageButton = await readFile(path.join(frontend, 'packages/ui-web/src/button.tsx'), 'utf8')
  const packagePrimitiveNames = ['input', 'card', 'badge', 'label', 'textarea', 'switch', 'checkbox', 'alert', 'tabs', 'select', 'dialog', 'tooltip', 'feedback', 'progress', 'skeleton', 'scroll-area', 'resizable', 'toast', 'theme-provider', 'icon-button', 'table', 'list', 'navigation', 'popover', 'sheet', 'drawer']
  const productPrimitiveNames = ['input', 'card', 'badge', 'label', 'textarea', 'switch', 'checkbox', 'alert', 'tabs', 'select', 'dialog', 'tooltip', 'feedback', 'progress', 'skeleton', 'scroll-area', 'resizable', 'toast']
  const packagePrimitives = await Promise.all(packagePrimitiveNames.map((name) => readFile(path.join(frontend, `packages/ui-web/src/${name}.tsx`), 'utf8')))
  const productPrimitives = await Promise.all(productPrimitiveNames.map((name) => readFile(path.join(frontend, `src/components/ui/${name}.tsx`), 'utf8')))
  const productButton = await readFile(path.join(frontend, 'src/components/ui/button.tsx'), 'utf8')
  const rootManifest = JSON.parse(await readFile(path.join(frontend, 'package.json'), 'utf8'))
  assert.equal(manifest.name, '@notemeld/ui-web')
  assert.equal(manifest.version, '0.1.0')
  assert.match(manifest.scripts.typecheck, /tsc -p tsconfig\.json/)
  assert.match(manifest.scripts.test, /node --test/)
  assert.match(manifest.scripts.build, /tsc -p tsconfig\.build\.json/)
  assert.match(manifest.scripts.lint, /tsc -p tsconfig\.json/)
  assert.match(manifest.scripts['test:a11y'], /node --test/)
  assert.match(manifest.scripts['test:visual'], /node --test/)
  assert.equal(rootManifest.dependencies['@notemeld/ui-web'], 'workspace:0.1.0')
  assert.match(manifest.exports['.'], /src\/index\.ts/)
  assert.match(packageIndex, /from '\.\/button'/)
  assert.match(packageButton, /from '\.\/cn'/)
  assert.doesNotMatch(packageButton, /@\//)
  assert.match(productButton, /from '@notemeld\/ui-web\/button'/)
  assert.match(packageIndex, /from '\.\/input'/)
  assert.match(packageIndex, /from '\.\/card'/)
  assert.match(packageIndex, /from '\.\/badge'/)
  assert.match(packageIndex, /from '\.\/label'/)
  assert.match(packageIndex, /from '\.\/textarea'/)
  assert.match(packageIndex, /from '\.\/switch'/)
  assert.match(packageIndex, /from '\.\/checkbox'/)
  assert.match(packageIndex, /from '\.\/alert'/)
  assert.match(packageIndex, /from '\.\/tabs'/)
  assert.match(packageIndex, /from '\.\/select'/)
  assert.match(packageIndex, /from '\.\/dialog'/)
  assert.match(packageIndex, /from '\.\/tooltip'/)
  assert.match(packageIndex, /from '\.\/feedback'/)
  assert.match(packageIndex, /from '\.\/progress'/)
  assert.match(packageIndex, /from '\.\/skeleton'/)
  assert.match(packageIndex, /from '\.\/scroll-area'/)
  assert.match(packageIndex, /from '\.\/resizable'/)
  assert.match(packageIndex, /from '\.\/toast'/)
  assert.match(packageIndex, /from '\.\/theme-provider'/)
  assert.match(packageIndex, /from '\.\/popover'/)
  assert.match(manifest.exports['./tokens.css'], /src\/tokens\.css/)
  assert.match(await readFile(path.join(frontend, 'packages/ui-web/src/tokens.css'), 'utf8'), /--nm-color-accent/)
  for (const source of packagePrimitives) assert.doesNotMatch(source, /@\//)
  for (const source of productPrimitives) assert.match(source, /@notemeld\/ui-web\//)
})
