const CloudLocaleContext = createContext<CloudLocaleContextValue | null>(null)

type CloudTranslate = (key: string, fallback: string) => string

export function localizeCloudError(message: string, t: CloudTranslate) {
  if (/device is not active for this account/i.test(message)) {
    return t('session.device-inactive', '当前设备已失效，正在重新连接…')
  }
  if (/cloud transport failed|transport failed|network error|failed to fetch/i.test(message)) {
    return t('session.transport-failed', '云端连接失败，请检查网络或稍后重试。')
  }
  if (/cloud agent provider unavailable|provider unavailable|model.*unavailable/i.test(message)) {
    return t('session.provider-unavailable', '云端模型暂不可用，请检查模型配置。')
  }
  if (/unauthorized|forbidden|permission denied|not allowed/i.test(message)) {
    return t('cloud.permission-denied', '当前账号没有执行此操作的权限。')
  }
  if (/conflict|revision|configuration changed/i.test(message)) {
    return t('cloud.config-conflict', '云端配置已发生变化，请刷新后重试。')
  }
  return t('cloud.request-failed', '云端请求失败，请稍后重试。')
}

function readLocale(): CloudLocale {
  return localStorage.getItem('notemeld-cloud-locale') === 'en-US' ? 'en-US' : 'zh-CN'
}

export function CloudLocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<CloudLocale>(readLocale)
  const setLocale = useCallback((next: CloudLocale) => {
    setLocaleState(next)
    localStorage.setItem('notemeld-cloud-locale', next)
    document.documentElement.lang = next
  }, [])
  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])
  const value = useMemo<CloudLocaleContextValue>(() => ({
    locale,
    setLocale,
    t: (key, fallback) => locale === 'en-US' ? messages[key] ?? fallback : fallback,
  }), [locale, setLocale])
  return <CloudLocaleContext.Provider value={value}>{children}</CloudLocaleContext.Provider>
}

export function useCloudLocale() {
  const context = useContext(CloudLocaleContext)
  if (!context) throw new Error('useCloudLocale must be used inside CloudLocaleProvider')
  return context
}
